"""Generate configs/a100/*.yaml from the reference T15 config (configs/temp_era_anom_15_100ep.yaml).

Every A100 run differs from the reference only in the keys set below, so results
stay comparable with the A4000 T15/T30 runs in docs/REVIEW_2026-11.md.
Common A100 changes: data from the exported .npy folder (data.npy_dir), and no
micro-batching for batch 512 (true full-batch BatchNorm, no "ghost BN").

    .venv/bin/python scripts/make_a100_configs.py      # rewrites configs/a100/
"""
import copy
import os

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, 'configs', 'temp_era_anom_15_100ep.yaml')
OUT = os.path.join(ROOT, 'configs', 'a100')
NPY_DIR = '../data/era5_npy/amazonia_daily'   # where the exported folder is unpacked

TEMP = dict(surf_vars=['mn2t', 'mx2t'], model='deit_small_temperature')
PREC = dict(surf_vars=['tp'], model='deit_small_precipitation')

# name -> (description, overrides). Overrides: K, batch, micro, epochs, warmup, lr, seed,
# vars (TEMP/PREC), var_transform, temporal_agg, remove_spatial_mean.
RUNS = {
    # A. Replication on clean full-batch BN: the paper needs >1 seed per configuration.
    **{f't15_s{s}': (f'T15 replication, seed {s}', dict(K=15, seed=s)) for s in (0, 1, 2)},
    **{f't30_s{s}': (f'T30 replication, seed {s}', dict(K=30, seed=s)) for s in (0, 1, 2)},
    # B. Over-clustering, regimes merged afterwards. Batch 1024 keeps ~10 days per
    #    prototype per batch under Sinkhorn; 200 epochs keeps the number of steps of a 100-epoch 512 run.
    't60_b1024': ('T60 over-clustering, batch 1024', dict(K=60, batch=1024, micro=512, epochs=200, warmup=30)),
    't100_b1024': ('T100 over-clustering, batch 1024', dict(K=100, batch=1024, micro=512, epochs=200, warmup=30)),
    # C. Pattern-only input: subtract each day's domain mean after the z-score (review: ~85 % of MSN
    #    separation is the domain-mean level). Tests whether pattern regimes carry ENSO signal.
    't30_nomean': ('T30 on pattern-only fields (domain mean removed)', dict(K=30, remove_spatial_mean=True)),
    # t30_nomean was still improving at epoch 100. Resuming it with more epochs would restart the cosine
    # LR/momentum/sharpen schedules mid-way (T_max = 1.25 * epochs), so train a fresh 200-epoch run instead.
    't30_nomean_200ep': ('T30 pattern-only, 200 epochs', dict(K=30, remove_spatial_mean=True, epochs=200, warmup=30)),
    # D. Precipitation only.
    'p30_daily_raw': ('P30 daily tp, same z-score as temperature (control)', dict(K=30, vars=PREC)),
    'p30_daily_cbrt': ('P30 daily tp, cube root before the z-score', dict(K=30, vars=PREC, var_transform={'tp': 'cbrt'})),
    'p30_roll30': ('P30 trailing 30-day tp sum per pixel, one sample per day',
                   dict(K=30, vars=PREC, temporal_agg={'kind': 'rolling', 'window': 30})),
    # Calendar-month sums: only 516 train months, so small batch, fewer prototypes, more epochs.
    'p10_monthly': ('P10 calendar-month tp sum per pixel, one sample per month',
                    dict(K=10, vars=PREC, temporal_agg={'kind': 'monthly'}, batch=128, epochs=500, warmup=50)),
}


def build(name, desc, o):
    with open(BASE) as f:
        cfg = yaml.safe_load(f)
    c = copy.deepcopy(cfg)
    v = o.get('vars', TEMP)
    batch = o.get('batch', 512)
    c['criterion'].update(num_proto=o['K'], batch_size=batch, micro_batch_size=o.get('micro', batch))
    d = c['data']
    d.update(surf_vars=v['surf_vars'], npy_dir=NPY_DIR,
             norm_means=[0.0] * len(v['surf_vars']), norm_stds=[1.0] * len(v['surf_vars']))
    for k in ('var_transform', 'temporal_agg', 'remove_spatial_mean'):
        if k in o:
            d[k] = o[k]
    # load_checkpoint 'auto': a requeued Slurm job (node reboot) resumes from -latest.
    c['meta'].update(model_name=v['model'], seed=o.get('seed', 0), use_bf16=True, load_checkpoint='auto')
    d['num_workers'] = 16  # FGV A100 node: 24 vCPUs for the whole job
    c['optimization'].update(epochs=o.get('epochs', 100), warmup=o.get('warmup', 15),
                             lr=o.get('lr', c['optimization']['lr']), val_patience=0, val_metric='msn')
    tag = f'a100-{name}'
    c['logging'].update(folder=f'checkpoint/{tag}/', write_tag=tag)
    header = (f'# {desc}\n# Generated by scripts/make_a100_configs.py from {os.path.relpath(BASE, ROOT)}; '
              f'edit the generator, not this file.\n')
    return header + yaml.safe_dump(c, sort_keys=False, default_flow_style=None)


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for name, (desc, o) in RUNS.items():
        with open(os.path.join(OUT, f'{name}.yaml'), 'w') as f:
            f.write(build(name, desc, o))
        print(f'configs/a100/{name}.yaml  {desc}')
